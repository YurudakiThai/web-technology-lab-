// 4. รองรับ Hot Module Replacement (HMR) ของ Vite
//    เมื่อคุณแก้ไขไฟล์นี้ Vite จะอัปเดตเฉพาะส่วนที่เปลี่ยน
//    โดยไม่ต้องรีเฟรชทั้งหน้า (สะดวกมาก)
