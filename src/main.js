// ตัวอย่าง: รอให้ DOM โหลดเสร็จแล้วจึงทำงาน
document.addEventListener('DOMContentLoaded', () => {
  console.log('✅ DOM พร้อมใช้งานแล้ว')
  
  // ตัวอย่าง: เปลี่ยนข้อความใน Element
  const heroTitle = document.querySelector('h1')
  if (heroTitle) {
    console.log('พบหัวข้อหลัก:', heroTitle.textContent)
  }
})

